"""Where may a sitting end on each page? Only where a salawat or prayer ends:
at a ۞ rosette (Dalail) or at the end of a paragraph (Kunuz, Mughnam, salawat).
Writes the last such point per page to src/core/cuts.ts (fractions of the page image)."""
import numpy as np, cv2, json, sys
from PIL import Image
MOB = '/home/claude/awradna/mobile'
D = f'{MOB}/assets/pages'
sys.path.insert(0, MOB)
def ink(id_, raw=False):
    a = np.array(Image.open(f'{D}/p{id_}.webp').split()[3])
    if raw: return a
    # remove the frame's vertical rules (columns inked along most of the page)
    H = a.shape[0]; cov = (a[int(H*0.2):int(H*0.8)] > 110).mean(0)
    a = a.copy(); a[:, cov > 0.5] = 0
    for c in np.where(cov > 0.5)[0]: a[:, max(0, c-3):c+4] = 0
    return a
TPL = ink('72', True)[121:155, 235:270].astype(np.float32)
def rosettes(a):
    r = cv2.matchTemplate(a.astype(np.float32), TPL, cv2.TM_CCOEFF_NORMED)
    ys, xs = np.where(r > 0.62); pts = []
    for y, x, v in sorted(zip(ys, xs, r[ys, xs]), key=lambda t: -t[2]):
        if all(abs(y - py) > 15 or abs(x - px) > 15 for py, px in pts): pts.append((int(y), int(x)))
    h, w = TPL.shape
    return [(y + h // 2, x) for y, x in pts]          # x = left edge of the rosette (its end, in RTL)
def text_lines(a):
    H, W = a.shape; full = (a > 110).sum(1)
    rule = [y for y in range(H) if full[y] > 0.6 * W]
    top = max([y for y in rule if y < H * 0.25], default=0) + 6
    bot = min([y for y in rule if y > H * 0.75], default=H) - 6
    rows = (a[:, 70:W - 70] > 110).sum(1)
    bands = []; y = top
    while y < bot:
        if rows[y] > 6:
            y0 = y
            while y < bot and rows[y] > 6: y += 1
            if y - y0 > 14: bands.append([y0, y])
        y += 1
    merged = []
    for b in bands:
        if merged and b[0] - merged[-1][1] < 12: merged[-1][1] = b[1]
        else: merged.append(b)
    L = [b for b in merged if b[1] - b[0] > 28]
    ext = []
    for y0, y1 in L:
        cols = np.where((a[y0:y1, 70:W - 70] > 110).sum(0) > 0)[0] + 70
        ext.append((int(cols.min()), int(cols.max())) if len(cols) else (70, W - 70))
    return L, ext, bot
QURAN = set()
for a, b in [(62, 65), (97, 103), (128, 132), (159, 167), (200, 202), (228, 234), (267, 269)]: QURAN.update(str(p) for p in range(a, b + 1))
import re
ts = open(f'{MOB}/src/core/pages.ts').read()
ids = re.findall(r"'([0-9]+[ab]?)': require\('\.\./\.\./assets/pages/", ts)
out = {}; stats = {'clean': 0, 'partial': 0, 'none': 0, 'startsep': 0}
for id_ in dict.fromkeys(ids):
    if not id_.rstrip('ab').isdigit() or int(id_.rstrip('ab')) < 27: continue
    a = ink(id_); H, W = a.shape
    L, ext, bot = text_lines(a)
    if not L or id_ in QURAN: out[id_] = None; stats['none'] += 1; continue
    left_margin = min(e[0] for e in ext); right_margin = max(e[1] for e in ext)
    cuts = []   # (line, x): text on that line left of x belongs to what follows
    for y, x in rosettes(a):
        li = next((i for i, (y0, y1) in enumerate(L) if y0 - 8 <= y <= y1 + 8), -1)
        if li >= 0: cuts.append((li, x))
    for i, (lo, hi) in enumerate(ext):
        if lo - left_margin > 90 and right_margin - hi < 40: cuts.append((i, left_margin - 1))   # a short line: end of a paragraph
    starts_sep = any(li == 0 and right_margin - x < 70 for li, x in [(c[0], c[1] + TPL.shape[1]) for c in cuts])
    if starts_sep: stats['startsep'] += 1
    if not cuts: out[id_] = {'none': True, 'startsSep': starts_sep}; stats['none'] += 1; continue
    li, x = max(cuts, key=lambda c: (c[0], -c[1]))
    last = len(L) - 1
    clean = li == last and x - ext[last][0] < 45
    stats['clean' if clean else 'partial'] += 1
    y0, y1 = L[li]
    out[id_] = {'clean': clean, 'startsSep': starts_sep, 'top': round(y0 / H, 4), 'bottom': round(min(H, y1 + 6) / H, 4), 'x': round(x / W, 4)}
print(stats)
js = json.dumps(out, separators=(',', ':'))
open(f'{MOB}/src/core/cuts.ts', 'w').write(
 '// Generated by scripts/cuts.py. For each book page: the last point where a salawat or prayer ends\n'
 '// (a ۞ rosette, or the end of a paragraph), as fractions of the page image. A sitting may only end there.\n'
 '// clean: the page itself ends there. none: no such point on the page (a long prayer continues).\n'
 'export type Cut = { clean?: boolean; startsSep?: boolean; none?: boolean; top?: number; bottom?: number; x?: number } | null;\n'
 f'export const CUTS: Record<string, Cut> = {js};\n')
