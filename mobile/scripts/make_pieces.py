"""Pages shared between two days are cut into pieces at a clean break, rendered exactly like
make_all_pages.py, then src/core/pages.ts is rebuilt from every image in assets/pages.
  276, 279, 280, 281, 282: the Mashishiyya Mamzuja (pp. 275–284) is spread over the seven days;
  each share ends at the end of a paragraph (279: before «(يا أوّل)»). Sunday reads the whole closing set
  (Ayat al-Kursi to the end), so 283 is not cut and 282 is cut twice.
  286, 287, 291: the 45 numbered salawat (pp. 285–292) are spread over the seven days; each cut
  sits just above the number that starts a day's share (positions from the PDF text layer).
Usage: python3 scripts/make_pieces.py book.pdf"""
import sys, os, json
import numpy as np, pymupdf
from PIL import Image
MOB = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DIR = os.path.join(MOB, 'assets/pages')
d = pymupdf.open(sys.argv[1]); OFF, DPI = 2, 150
X0, X1, Y0, Y1 = 0.165, 0.835, 0.20, 0.955
def render(printed, y0, y1):
    p = d[printed + OFF - 1]; r = p.rect
    pix = p.get_pixmap(dpi=DPI, clip=pymupdf.Rect(r.width * X0, r.height * y0, r.width * X1, r.height * y1), colorspace=pymupdf.csGRAY)
    return Image.frombytes('L', [pix.width, pix.height], pix.samples)
def save(key, im):
    a = Image.fromarray((255 - np.clip((np.asarray(im, dtype=np.float32) - 10) / 0.92, 0, 255)).astype(np.uint8), 'L')
    Image.merge('RGBA', [Image.new('L', im.size, 0)] * 3 + [a]).save(os.path.join(DIR, f'p{key}.webp'), 'WEBP', quality=62, alpha_quality=50, method=6)
# the line that starts the second piece (page fraction of its top, from the PDF text layer:
# number 15 at .7571, 22 at .7835, 40 at .4786; «(يا أوّل)» on 279). The cut goes in the middle of the
# blank gap above that line, so no mark of either line is clipped.
STARTS = {279: 0.20 + (1108 / 1768) * (Y1 - Y0), 286: 0.7571, 287: 0.7835, 291: 0.4786,
          # the Mamzuja over seven days: each share starts at a new paragraph
          276: 0.6740, 280: 0.6971, 281: 0.6398, 282: [0.4067, 0.6347]}
def gap_cut(pg, top):
    im = np.asarray(render(pg, Y0, Y1)); H = im.shape[0]
    ink = ((255 - im[:, 60:-60]) > 60).sum(1) > 0
    y = int((top - Y0) / (Y1 - Y0) * H)
    while y > 0 and ink[y]: y -= 1          # step up out of the starting line
    lo = y
    while lo > 0 and not ink[lo]: lo -= 1   # to the bottom of the line above
    return Y0 + ((lo + y) / 2) / H * (Y1 - Y0)
CUTS = {pg: [gap_cut(pg, t) for t in (ts if isinstance(ts, list) else [ts])] for pg, ts in STARTS.items()}
print('cuts', {k: [round(v, 4) for v in vs] for k, vs in CUTS.items()})
for pg, ys in CUTS.items():
    edges = [Y0] + ys + [Y1]
    for j in range(len(edges) - 1): save(f'{pg}{"abc"[j]}', render(pg, edges[j], edges[j + 1]))
    full = os.path.join(DIR, f'p{pg}.webp')
    if os.path.exists(full): os.remove(full)   # only the pieces are read
size = {}
for f in os.listdir(DIR):
    if f.endswith('.webp'): size[f[1:-5]] = list(Image.open(os.path.join(DIR, f)).size)
keys = sorted(size, key=lambda k: (int(k.rstrip('abc')), k))
rows = '\n'.join(f"  '{k}': require('../../assets/pages/p{k}.webp')," for k in keys)
open(os.path.join(MOB, 'src/core/pages.ts'), 'w').write(
  '// Generated by scripts/make_all_pages.py and scripts/make_pieces.py: book page images bundled in the app (printed page id -> image).\n/* eslint-disable */\n'
  f'export const PAGE_IMAGES: Record<string, number> = {{\n{rows}\n}};\n'
  f'export const PAGE_SIZE: Record<string, [number, number]> = {json.dumps({k: size[k] for k in keys})};\n')
print({k: size[k] for k in keys if k.rstrip('ab') in ('273', '279', '286', '287', '291')}, len(keys), 'images')
