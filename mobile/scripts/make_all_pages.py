"""Render every book page the app shows, in two looks, and write src/core/pages.ts.
  One WebP per page holding only the ink, as alpha (transparent paper). The app tints it:
  dark ink on paper by day, ivory ink on lapis by night, from the same file.
Usage: python3 make_all_pages.py book.pdf <mobile dir>
"""
import sys, json, os
import numpy as np
import pymupdf
from PIL import Image

src, mob = sys.argv[1], sys.argv[2]
day_dir, night_dir = os.path.join(mob, 'assets/pages'), os.path.join(mob, 'assets/pages-night')
import shutil
shutil.rmtree(night_dir, ignore_errors=True)
for d_ in (day_dir,):
    os.makedirs(d_, exist_ok=True)
    for f in os.listdir(d_): os.remove(os.path.join(d_, f))

d = pymupdf.open(src)
OFF, DPI = 2, 150
X0, X1, Y0, Y1 = 0.165, 0.835, 0.20, 0.955

ranges = [
    (9, 24),                                   # daily wird: الأساس، المسبعات، الوظيفة، حزب البحر
    (27, 65), (69, 103), (107, 132), (135, 167), (171, 202), (205, 234), (237, 269),   # days (+ the day's surah)
    (274, 292),
]
pages = [p for a, b in ranges for p in range(a, b + 1)]

def render(printed, y0=Y0, y1=Y1):
    p = d[printed + OFF - 1]; r = p.rect
    clip = pymupdf.Rect(r.width * X0, r.height * y0, r.width * X1, r.height * y1)
    pix = p.get_pixmap(dpi=DPI, clip=clip, colorspace=pymupdf.csGRAY)
    return Image.frombytes('L', [pix.width, pix.height], pix.samples)

size = {}
def save(key, im):
    a = Image.fromarray((255 - np.clip((np.asarray(im, dtype=np.float32) - 10) / 0.92, 0, 255)).astype(np.uint8), 'L')
    rgba = Image.merge('RGBA', [Image.new('L', im.size, 0)] * 3 + [a])
    rgba.save(os.path.join(day_dir, f'p{key}.webp'), 'WEBP', quality=62, alpha_quality=50, method=6)
    size[key] = [im.width, im.height]

for pr in pages: save(str(pr), render(pr))
split = 0.20 + (495 / 1054) * (0.95 - 0.20)
save('273a', render(273, Y0, split)); save('273b', render(273, split, Y1))

keys = sorted(size, key=lambda k: (int(k.rstrip('ab')), k))
def table(name, folder):
    rows = '\n'.join(f"  '{k}': require('../../assets/{folder}/p{k}.webp')," for k in keys)
    return f'export const {name}: Record<string, number> = {{\n{rows}\n}};\n'
ts = ('// Generated by scripts/make_all_pages.py: book page images bundled in the app (printed page id -> image).\n/* eslint-disable */\n'
      + table('PAGE_IMAGES', 'pages')
      + f'export const PAGE_SIZE: Record<string, [number, number]> = {json.dumps(size)};\n')
open(os.path.join(mob, 'src/core/pages.ts'), 'w').write(ts)
tot = sum(os.path.getsize(os.path.join(dd, f)) for dd in (day_dir,) for f in os.listdir(dd))
print(len(size), 'pages,', round(tot / 1048576, 1), 'MB')
